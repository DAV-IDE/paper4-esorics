    bn = "per_window" if est == "Shannon" else "none"
    q = df[(df.scenario == sc) & (df.cfg == cfg) & (df.est == est) & (df.variant == var) & (df.rule == rule) & (df.binning == bn)]
    assert len(q) == 1, (sc, cfg, est, var, rule); return q.iloc[0]
