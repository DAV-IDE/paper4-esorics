def dwin_med(cal, est, bn, var, rule, src="real_second_full_cells.csv"):
    q = rdw[(rdw.source_file == src) & (rdw.calibration == cal) & (rdw.est == est) & (rdw.binning == bn) & (rdw.variant == var) & (rdw.rule == rule) & (rdw.detected == True)]
