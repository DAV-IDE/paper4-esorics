for s, e, c in rows:
    r = d[(d.scenario == s) & (d.est == e) & (d.cfg == c)].iloc[0]
    b += f"{SCN[s]} & ({EST[e]}, $C_{c[1]}$) & {num(r.seed42_delay)} & {num(r.seed42_fp)} & {r.n_detected:.0f}/30 & {miqr(r.delay_median, r.delay_q1, r.delay_q3, 1 if r.delay_median % 1 else 0)} & {num(r.fp_pre_median,1) if r.fp_pre_median%1 else num(r.fp_pre_median)} \\\\\n"
    NUM[f"T1_{s}_{e}_{c}"] = dict(seed42=r.seed42_delay, med=r.delay_median, q1=r.delay_q1, q3=r.delay_q3, det=r.n_detected)
b += "\\bottomrule\n\\end{tabular}\n"
wr("tab_synth_published_vs_multiseed.tex", h, b)

