def agg(df, cal, est, bn, var, rule):
    q = df[(df.calibration == cal) & (df.est == est) & (df.binning == bn) & (df.variant == var) & (df.rule == rule)]
    det = q[q.detected == True]
    return dict(n=len(q), det=int(q.detected.sum()), dmed=det.delay.median(), dwin=dwin_med(cal, est, bn, var, rule)[0], fph=q.FP_per_hour.median(),
                fph_max=q.FP_per_hour.max(), auc_min=q.AUCROC_persample.min(), auc_max=q.AUCROC_persample.max(),
                fex=int(q.fires_excluded.sum()))
