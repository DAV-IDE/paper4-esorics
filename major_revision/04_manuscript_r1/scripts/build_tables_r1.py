#!/usr/bin/env python3
"""Build every LaTeX table and figure of the R1 manuscript from FROZEN artefacts.

Inputs  : major_revision/03_r1_experiments/results/** (verified against
          SHA256SUMS_R1.txt and SHA256SUMS_R1_C.txt before running).
Outputs : 04_manuscript_r1/tables_r1/*.tex, figures/pareto_pcap.pdf,
          tables_r1/claim_numbers.json (every number quoted in the text).
No experiment is re-run; this script only reads CSV/JSON results, aggregates
them deterministically and formats them. Each .tex carries its source files.
"""
import gzip, hashlib, json, os, sys
import numpy as np, pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
M = os.path.dirname(HERE)
R = os.path.join(os.path.dirname(M), "03_r1_experiments")
RES = os.path.join(R, "results")
T = os.path.join(M, "tables_r1"); F = os.path.join(M, "figures")
os.makedirs(T, exist_ok=True); os.makedirs(F, exist_ok=True)
NUM = {}

def sha(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest()

def rd(rel):
    p = os.path.join(RES, rel)
    return pd.read_csv(p), f"% source: results/{rel} (sha256 {sha(p)[:16]})\n"

def wr(name, header, body):
    with open(os.path.join(T, name), "w") as f:
        f.write("% AUTO-GENERATED by scripts/build_tables_r1.py -- do not edit by hand\n" + header + body)

def pct(x, d=0):
    return "--" if pd.isna(x) else f"{100*x:.{d}f}"

def num(x, d=0):
    return "--" if pd.isna(x) else (f"{x:.{d}f}" if d else f"{int(round(x))}")

def miqr(m, a, b, d=0):
    return "--" if pd.isna(m) else f"{num(m,d)} [{num(a,d)}--{num(b,d)}]"

EST = {"Shannon": r"$\Hsh$", "Sample": r"$\Hsa$", "Permutation": r"$\Hpe$"}
CFG = {"C1": (128, 1), "C2": (64, 1), "C3": (256, 1), "C4": (128, 4), "C5": (128, 8)}
SCN = {"drift_gradual": "Drift", "shock": "Shock"}

# --------------------------------------------------------------------------
# T1  published Table 4 rows: seed 42 vs 30-seed distribution (legacy pipeline)
d, h = rd("04_stats/legacy_published_multiseed_synthetic.csv")
rows = [("drift_gradual", "Shannon", "C1"), ("drift_gradual", "Shannon", "C3"),
        ("shock", "Permutation", "C1"), ("shock", "Shannon", "C2")]
