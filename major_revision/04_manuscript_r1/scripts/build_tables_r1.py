def slope(g):
    x, y = np.log(g.triples.values), np.log(g.median_ms.values)
    A = np.vstack([x, np.ones_like(x)]).T; coef, res, *_ = np.linalg.lstsq(A, y, rcond=None)
    n = len(x); s2 = float(((y - A @ coef) ** 2).sum()) / (n - 2); se = np.sqrt(s2 / ((x - x.mean()) ** 2).sum())
    from scipy import stats
    tq = stats.t.ppf(0.975, n - 2)
    return coef[0], coef[0] - tq * se, coef[0] + tq * se
