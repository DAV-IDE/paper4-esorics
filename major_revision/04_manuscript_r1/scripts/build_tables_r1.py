def pick(sc, cfg, est, var, rule, binning=None):
    q = d[(d.scenario == sc) & (d.cfg == cfg) & (d.est == est) & (d.variant == var) & (d.rule == rule)]
    q = q[q.binning == (binning or ("per_window" if est == "Shannon" else "none"))]
    return q.iloc[0]
ci, hci = rd("04_stats/synthetic_cell_median_ci.csv")
dw, hdw = rd("04_stats/delay_windows_synthetic_cells.csv")
KEY = ["scenario", "cfg", "est", "binning", "variant", "rule"]
